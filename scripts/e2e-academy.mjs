// CampIL Academy: search by need → knot page → step viewer → quiz → learned & favourite → progress.
import { chromium } from 'playwright-core';
const OUT = process.argv[2]; const BASE = 'http://localhost:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.env.CI ? undefined : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'he-IL', deviceScaleFactor: 2 });
await ctx.route(/open-meteo|overpass|osrm|nominatim|openfreemap|fonts\./, r => r.abort());
const p = await ctx.newPage(); const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE + '#/academy'); await p.waitForTimeout(1200);
console.log('academy lists knots and guides:', (await p.locator('main ul li').count()) >= 11);
await p.getByLabel('מה צריך לעשות?').fill('אני רוצה למתוח חבל לאוהל'); await p.waitForTimeout(300);
const first = (await p.locator('main ul li').first().innerText());
console.log('search by need → taut-line hitch first:', first.includes('קשר מתיחה לחבל אוהל'));
await p.locator('ul li a').first().click(); await p.waitForTimeout(800);
console.log('safety note shown:', (await p.getByRole('note').innerText()).includes('לא לטיפוס'));
const status = () => p.locator('p[aria-live="polite"]').first().innerText();
console.log('starts at step 1:', (await status()).includes('שלב 1/4'));
await p.getByRole('button', { name: 'הבא' }).click(); await p.waitForTimeout(300);
console.log('next → step 2:', (await status()).includes('שלב 2/4'));
await p.getByRole('radio', { name: 'מהיר' }).click();
await p.getByRole('button', { name: 'ניגון' }).click(); await p.waitForTimeout(4200);
console.log('play reaches the last step:', (await status()).includes('שלב 4/4'));
await p.screenshot({ path: `${OUT}/academy-knot.png`, fullPage: true });
await p.getByRole('button', { name: 'שלב 1: העבירו את החבל סביב היתד, והחזירו את הקצה לכיוון האוהל.' }).click(); await p.waitForTimeout(200);
console.log('jump to a step:', (await status()).includes('שלב 1/4'));
// quiz: pick the right answers
const quiz = p.getByRole('region', { name: /בדיקת ידע/ });
for (const t of ['בתוך הלולאה, לכיוון היתד', 'מחליקים את הקשר הרחק מהיתד', 'הקשר מחליק']) await p.getByRole('button', { name: t, exact: true }).click();
await p.getByRole('button', { name: /^סיום/ }).click(); await p.waitForTimeout(300);
console.log('perfect quiz marks it learned:', (await p.getByRole('button', { name: 'נלמד' }).count()) === 1);
await p.getByRole('button', { name: 'למועדפים' }).click();
await p.goto(BASE + '#/academy'); await p.waitForTimeout(600);
console.log('progress shows 1 learned:', (await p.getByText(/^1\/\d+ נלמדו$/).count()) === 1);
await p.getByRole('group', { name: 'קטגוריות' }).getByRole('button', { name: 'מועדפים' }).click(); await p.waitForTimeout(200);
console.log('favourites filter shows it:', (await p.locator('main ul li').count()) === 1);
await p.reload(); await p.waitForTimeout(800);
console.log('progress persisted:', (await p.getByText(/^1\/\d+ נלמדו$/).count()) === 1);
console.log('errors:', errors.length ? errors.join(' | ') : 'none');
await b.close();
