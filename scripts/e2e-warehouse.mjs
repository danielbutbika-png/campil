// Gear warehouse: sizes, weight, ownership and periodic checks are entered, persist, feed the totals and filters.
import { chromium } from 'playwright-core';
const OUT = process.argv[2]; const BASE = 'http://localhost:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.env.CI ? undefined : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'he-IL', deviceScaleFactor: 2 });
await ctx.route(/open-meteo|overpass|osrm|nominatim|openfreemap|fonts\./, r => r.abort());
const p = await ctx.newPage(); const errors = [];
p.on('pageerror', e => errors.push(e.message));
const iso = m => { const d = new Date(); d.setMonth(d.getMonth() + m); return d.toLocaleDateString('sv-SE'); };
const stats = () => p.locator('section[aria-labelledby="wh-h"]').innerText();

await p.goto(BASE); await p.waitForTimeout(1200);
await p.goto(BASE + '#/gear'); await p.waitForTimeout(1000);
const before = await stats();
const first = p.locator('section ul li button').first();
const name = (await first.locator('span.font-semibold').innerText()).trim();
await first.click(); await p.waitForTimeout(300);
await p.getByLabel('אורך בס״מ').fill('60'); await p.getByLabel('רוחב בס״מ').fill('20'); await p.getByLabel('גובה בס״מ').fill('20');
console.log('volume computed from dimensions shown:', (await p.getByPlaceholder('לפי המידות: 24').count()) > 0);
await p.getByLabel('משקל ליחידה (ק״ג)').fill('4.5');
await p.getByRole('textbox', { name: 'מושאל מ־' }).fill('משפחת לוי');
await p.getByRole('combobox', { name: 'בדיקה תקופתית' }).selectOption('6');
await p.getByLabel('נבדק לאחרונה').fill(iso(-7));
console.log('due notice in editor:', (await p.getByText(/הגיע זמן בדיקה/).count()) > 0);
await p.getByRole('button', { name: 'שמירה' }).click(); await p.waitForTimeout(400);
const row = p.locator('section ul li button', { hasText: name }).first();
const sub = await row.innerText();
console.log('row shows weight, size and owner:', sub.includes('4.5 ק״ג') && sub.includes('60×20×20') && sub.includes('מושאל ממשפחת לוי'));
console.log('row flagged for check:', sub.includes('לבדיקה'));
const after = await stats();
console.log('stats changed (weighed / borrowed / due):', before !== after && /1 מתוך \d+ נשקלו/.test(after) && after.includes('מושאלים (1)'));
await p.getByRole('button', { name: /^לבדיקה/ }).click(); await p.waitForTimeout(200);
console.log('check filter shows the item:', (await p.locator('section ul li button', { hasText: name }).count()) > 0);
await p.getByRole('button', { name: /^מושאלים/ }).click(); await p.waitForTimeout(200);
console.log('borrowed filter shows only it:', (await p.locator('section ul li').count()) === 1);
await p.screenshot({ path: `${OUT}/warehouse.png`, fullPage: true });
await p.reload(); await p.waitForTimeout(1000);
await p.locator('section ul li button', { hasText: name }).first().click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'נבדק היום' }).click(); await p.waitForTimeout(200);
console.log('persisted after reload:', (await p.getByLabel('משקל ליחידה (ק״ג)').inputValue()) === '4.5');
console.log('"checked today" clears the due notice:', (await p.getByText(/הבדיקה הבאה/).count()) > 0);
await p.getByRole('button', { name: 'שמירה' }).click(); await p.waitForTimeout(300);
console.log('no longer flagged:', !(await p.locator('section ul li button', { hasText: name }).first().innerText()).includes('לבדיקה'));
console.log('errors:', errors.length ? errors.join(' | ') : 'none');
await b.close();
