// Intelligence Engine (rules): recommendation cards with what/why/what to do/evidence/certainty, done & dismiss,
// a transparent readiness checklist, an honest "rules-based, no AI" label — and the design-system page.
import { chromium } from 'playwright-core';
const OUT = process.argv[2]; const BASE = 'http://localhost:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.env.CI ? undefined : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'he-IL', deviceScaleFactor: 2 });
await ctx.route(/open-meteo|overpass|osrm|nominatim|openfreemap|fonts\./, r => r.abort());
const p = await ctx.newPage(); const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE); await p.waitForTimeout(1000);
const z = n => String(n).padStart(2, '0'); const d = new Date(); d.setDate(d.getDate() + 1);
const tomorrow = `${d.getFullYear()}-${z(d.getMonth() + 1)}-${z(d.getDate())}`;
const tid = await p.evaluate(s => { const k = JSON.parse(localStorage.getItem('campil-v1')); const t = k.state.trips[0];
  Object.assign(t, { start: s, end: s, example: false });
  t.packing.push({ id: 'pw1', name: 'פנס ראש', category: 'power', qty: 2, reason: 'x', source: 'manual', packed: false });
  t.meals = [{ id: 'm1', day: 0, type: 'lunch', recipeId: 'shakshuka', servings: 1 }];
  localStorage.setItem('campil-v1', JSON.stringify(k)); return t.id; }, tomorrow);
await p.goto(BASE + `#/trip/${tid}`); await p.reload(); await p.waitForTimeout(1500);
console.log('honest label — rules-based, no AI:', (await p.getByText('מבוסס כללים — בלי AI').count()) > 0);
const charge = p.locator('li[data-rec="charge"]');
console.log('charge card: what was found + what to do + one action:', (await charge.count()) === 1 && (await charge.innerText()).includes('מה לעשות') && (await charge.getByRole('link', { name: 'לרשימת הציוד' }).count()) === 1);
const food = p.locator('li[data-rec="food-count"]');
console.log('food card: dishes for fewer people than are coming:', (await food.count()) === 1 || (await p.getByRole('button', { name: /עוד \d+ המלצות/ }).count()) === 1);
await charge.getByRole('button', { name: 'למה?' }).click(); await p.waitForTimeout(200);
const ev = await charge.getByLabel('על מה ההמלצה מבוססת').innerText();
console.log('"why?": evidence kinds, certainty, time, engine, source:', ev.includes('עובדה') && ev.includes('חישוב') && ev.includes('ודאות') && ev.includes('מנוע כללים'));
await charge.getByRole('button', { name: /לא רלוונטי/ }).click(); await p.waitForTimeout(400);
console.log('dismissed card disappears:', (await p.locator('li[data-rec="charge"]').count()) === 0);
await p.reload(); await p.waitForTimeout(1200);
console.log('…and stays dismissed after reload:', (await p.locator('li[data-rec="charge"]').count()) === 0);
await p.evaluate(id => { const k = JSON.parse(localStorage.getItem('campil-v1')); k.state.trips.find(t => t.id === id).packing.push({ id: 'pw2', name: 'מטען נייד', category: 'power', qty: 1, reason: 'x', source: 'manual', packed: false }); localStorage.setItem('campil-v1', JSON.stringify(k)); }, tid);
await p.reload(); await p.waitForTimeout(1200);
console.log('…until the facts change (a new item to charge):', (await p.locator('li[data-rec="charge"]').count()) === 1);
const rd = p.getByRole('list', { name: 'רשימת מוכנות' });
console.log('readiness: a transparent checklist with numbers and weights:', (await rd.locator('li').count()) >= 4 && (await rd.innerText()).includes('×3'));
await p.screenshot({ path: `${OUT}/intel.png`, fullPage: true });
await p.goto(BASE + '#/design'); await p.waitForTimeout(800);
const tbl = await p.locator('table').innerText();
console.log('design page: all measured pairs pass AA:', tbl.includes('✓') && !tbl.includes('✗'));
await p.screenshot({ path: `${OUT}/design.png`, fullPage: true });
console.log('errors:', errors.length ? errors.join(' | ') : 'none');
await b.close();
