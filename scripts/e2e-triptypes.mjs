// Trip Type Engine: pick a combination in the wizard → gear, tasks and checks of those types appear in the plan.
import { chromium } from 'playwright-core';
const OUT = process.argv[2]; const BASE = 'http://localhost:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.env.CI ? undefined : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'he-IL', deviceScaleFactor: 2 });
await ctx.route(/open-meteo|overpass|osrm|nominatim|openfreemap|fonts\./, r => r.abort());
const p = await ctx.newPage(); const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE); await p.waitForTimeout(1000);
await p.goto(BASE + '#/new'); await p.waitForTimeout(800);
for (const n of ['קמפינג משפחתי', 'מסלול רטוב', 'רכיבת אופניים']) await p.getByRole('button', { name: n, exact: true }).click();
console.log('three types selected:', (await p.locator('button[aria-pressed="true"]').count()) >= 3);
await p.getByLabel(/כמה אופניים/).fill('3');
await p.screenshot({ path: `${OUT}/types-wizard.png`, fullPage: true });
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'בחרו בשבילי' }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'בנו לי תוכנית' }).click(); await p.waitForTimeout(1500);
const tid = p.url().split('/trip/')[1].split('/')[0];
const ov = await p.locator('main').innerText();
console.log('checks card for the types with official sources:', ov.includes('לבדוק לפני היציאה — לפי סוג הטיול') && (await p.getByRole('link', { name: /רשות הטבע והגנים/ }).count()) > 0);
await p.goto(BASE + `#/trip/${tid}/gear`); await p.waitForTimeout(1200);
const gear = await p.locator('main').innerText();
console.log('water-hike gear in the list:', gear.includes('נעלי מים לכל משתתף') && gear.includes('שקיות אטומות לטלפונים ומסמכים'));
const helmet = await p.locator('li', { hasText: 'קסדה לכל רוכב' }).first().innerText();
console.log('helmets follow the answer (3):', /\b3\b/.test(helmet));
await p.goto(BASE + `#/trip/${tid}/tasks`); await p.waitForTimeout(800);
console.log('type task added:', (await p.locator('main').innerText()).includes('בגדי החלפה ומגבות בתיק נפרד'));
await p.goto(BASE + `#/trip/${tid}`); await p.waitForTimeout(800);
await p.getByRole('button', { name: /עריכה|עריכת פרטי הטיול/ }).first().click(); await p.waitForTimeout(400);
await p.getByRole('dialog').getByRole('button', { name: 'עם כלבים', exact: true }).click();
await p.getByRole('dialog').getByRole('button', { name: /שמירה/ }).click(); await p.waitForTimeout(1500);
await p.goto(BASE + `#/trip/${tid}/gear`); await p.waitForTimeout(1200);
console.log('editing types later updates gear (dog water):', (await p.locator('main').innerText()).includes('מים וקערה לכלב לדרך'));
console.log('errors:', errors.length ? errors.join(' | ') : 'none');
await b.close();
