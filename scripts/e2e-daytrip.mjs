// New day trip: search a destination (catalog + web), it goes into the route; "no food" skips menu and cooking gear.
import { chromium } from 'playwright-core';
const OUT = process.argv[2]; const BASE = 'http://localhost:4173/';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || (process.env.CI ? undefined : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'he-IL', deviceScaleFactor: 2 });
let webCalls = 0;
await ctx.route(/nominatim/, r => { webCalls++; r.fulfill({ json: [{ osm_type: 'node', osm_id: 123, lat: '32.9667', lon: '35.5000', type: 'peak', category: 'natural', name: 'הר ארבל', display_name: 'הר ארבל, ישראל', namedetails: { 'name:he': 'הר ארבל' }, extratags: {} }] }); });
await ctx.route(/open-meteo|overpass|osrm|openfreemap|fonts\.|wikipedia/, r => r.abort());
const p = await ctx.newPage(); const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto(BASE); await p.waitForTimeout(1000);
await p.goto(BASE + '#/new'); await p.waitForTimeout(700);
console.log('no search before choosing a day trip:', (await p.getByLabel('לאן נוסעים?').count()) === 0);
await p.getByRole('radio', { name: 'טיול יום' }).click(); await p.waitForTimeout(200);
const q = p.getByLabel('לאן נוסעים?');
await q.fill('עין גדי'); await p.waitForTimeout(200);
console.log('catalog matches while typing, no web request:', (await p.getByRole('list', { name: 'מהקטלוג של CampIL' }).locator('li').count()) > 0 && webCalls === 0);
await p.getByRole('list', { name: 'מהקטלוג של CampIL' }).getByRole('button').first().click(); await p.waitForTimeout(200);
console.log('catalog site added to the route:', (await p.getByRole('list', { name: 'יעדים במסלול' }).innerText()).includes('עין גדי'));
await q.fill('הר ארבל'); await p.getByRole('button', { name: 'חיפוש', exact: true }).click(); await p.waitForTimeout(400);
console.log('web search on submit only:', webCalls === 1);
await p.getByRole('list', { name: 'תוצאות מהרשת' }).getByRole('button').first().click(); await p.waitForTimeout(200);
console.log('web place added to the route:', (await p.getByRole('list', { name: 'יעדים במסלול' }).locator('li').count()) === 2);
await p.screenshot({ path: `${OUT}/daytrip-search.png`, fullPage: true });
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(500);
console.log('region already chosen from the destination:', (await p.getByRole('button', { name: /^המשך/ }).count()) === 1);
await p.getByRole('button', { name: /^המשך|בחרו בשבילי/ }).click(); await p.waitForTimeout(400);
// participants: make sure everyone has a gender
for (const g of await p.getByRole('radiogroup', { name: /^מגדר של/ }).all()) if (!(await g.locator('[aria-checked=true]').count())) await g.getByRole('radio', { name: 'נקבה' }).click();
await p.getByRole('radio', { name: 'בלי אוכל' }).click(); await p.waitForTimeout(200);
console.log('diet editor hidden when no food:', (await p.getByText('לא נבנה תפריט ורשימת קניות').count()) === 1);
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'המשך' }).click(); await p.waitForTimeout(400);
const sum = await p.locator('dl').innerText();
console.log('summary: no food, both places:', sum.includes('בלי אוכל') && sum.includes('הר ארבל') && sum.includes('עין גדי'));
await p.getByRole('button', { name: 'בנו לי תוכנית' }).click(); await p.waitForTimeout(1500);
const t = await p.evaluate(() => JSON.parse(localStorage.getItem('campil-v1')).state.trips.at(-1));
console.log('trip named after the destination:', t.name.startsWith('טיול יום ל'), t.name);
console.log('route in schedule:', t.schedule.some(x => x.title.includes('עין גדי')) && t.schedule.some(x => x.title === 'הר ארבל'));
console.log('no meals, no meal slots in schedule:', t.noFood === true && t.meals.length === 0 && !t.schedule.some(x => x.kind === 'meal'));
console.log('no cooking gear, water kept:', !t.packing.some(x => x.category === 'kitchen') && t.packing.some(x => x.name === 'מים לשתייה'));
await p.goto(BASE + `#/trip/${t.id}/meals`); await p.waitForTimeout(700);
console.log('meals tab explains no food:', (await p.getByRole('heading', { name: 'בלי אוכל בטיול הזה' }).count()) === 1);
await p.getByRole('button', { name: 'לתכנן אוכל בכל זאת' }).click(); await p.waitForTimeout(600);
console.log('can switch back to planning food:', (await p.evaluate(id => JSON.parse(localStorage.getItem('campil-v1')).state.trips.find(x => x.id === id).meals.length, t.id)) > 0);
console.log('errors:', errors.length ? errors.join(' | ') : 'none');
await b.close();
